export function isLocale(value: string | null | undefined): value is Locale {
  return typeof value === 'string' && (supportedLocales as readonly string[]).includes(value)
}

export function getStoredLocale(): Locale {
  const stored = typeof window === 'undefined' ? null : window.localStorage.getItem(storageKey)
  if (isLocale(stored)) return stored
  const browser = typeof navigator === 'undefined' ? undefined : navigator.language?.split('-')[0]
  return isLocale(browser) ? browser : 'en'
}

export function translate(locale: Locale, key: string, values?: Interpolation): string {
  const text = catalogs[locale][key] ?? key
  return values ? text.replace(/{{(\w+)}}/g, (_, name: string) => String(values[name] ?? '')) : text
}

interface LocaleContextValue {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: (key: string, values?: Interpolation) => string
}

const LocaleContext = createContext<LocaleContextValue | null>(null)

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(getStoredLocale)

  const setLocale = (next: Locale) => {
    window.localStorage.setItem(storageKey, next)
    setLocaleState(next)
  }

  useEffect(() => {
    document.documentElement.lang = locale
  }, [locale])

  const value = useMemo(() => ({ locale, setLocale, t: (key: string, values?: Interpolation) => translate(locale, key, values) }), [locale])
  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>
}

export function useI18n() {
  const context = useContext(LocaleContext)
  if (!context) throw new Error('useI18n must be used inside LocaleProvider')
  return context
}
